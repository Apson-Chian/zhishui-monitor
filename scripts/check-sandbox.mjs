import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const context={window:{}};
vm.runInNewContext(readFileSync(new URL('../dist/assets/hydro-sandbox.js',import.meta.url),'utf8'),context);
const H=context.window.HydroSandbox;
const source=readFileSync(new URL('../dist/assets/app.js',import.meta.url),'utf8');
const seeds=JSON.parse(source.match(/const stations=(\[[\s\S]*?\]);/)[1]);
const model=H.createModel(seeds);
const c={scope:'qinhuai',rain:90,minute:15,gate:0,gateAt:0};
const before=model.sample({...c,minute:0}),early=model.sample(c),late=model.sample({...c,minute:60});
assert.deepEqual(JSON.parse(JSON.stringify(before.map(s=>s.level))),seeds.map(s=>s.base));
assert.ok(early[2].level>before[2].level);
assert.equal(early[0].level,before[0].level);
assert.equal(early[1].level,before[1].level);
assert.ok(late[0].level>early[0].level && late[1].level>early[1].level);
assert.equal(late[3].level,seeds[3].base,'another water body must be isolated');
const lake=model.sample({scope:'lake',rain:90,minute:60,gate:100});
const lakeWithoutGate=model.sample({scope:'lake',rain:90,minute:60,gate:0});
assert.deepEqual(JSON.parse(JSON.stringify(lake)),JSON.parse(JSON.stringify(lakeWithoutGate)),'separate lakes have no virtual gate propagation');
const closed=model.sample({...c,minute:50,gate:0}),opened=model.sample({...c,minute:50,gate:100,gateAt:20});
assert.ok(opened[2].level<closed[2].level&&opened[2].flow>closed[2].flow);
assert.ok(opened[1].level>closed[1].level&&opened[1].flow>closed[1].flow);
assert.deepEqual(JSON.parse(JSON.stringify(late)),JSON.parse(JSON.stringify(model.sample({...c,minute:60}))),'seeking must reproduce the same state');
assert.ok(model.sample({...c,rain:999,minute:999}).every(s=>Number.isFinite(s.level)&&s.flow>=0));
assert.deepEqual([H.stage(8,10),H.stage(9.6,10),H.stage(10,10),H.stage(10.6,10)],[0,1,2,3]);
// Replay must retain the past, controls must act progressively, and rainfall must end.
const rainfall=H.changes([],0,90,40);
const original={scope:'qinhuai',rain:90,rainEvents:rainfall,minute:30};
const stopped={...original,rain:0,rainEvents:H.changes(rainfall,30,0)};
for(const minute of [0,10,25,30])assert.deepEqual(JSON.parse(JSON.stringify(model.sample({...original,minute}))),JSON.parse(JSON.stringify(model.sample({...stopped,minute}))),'stopping now must not rewrite the past');
assert.ok(model.sample({...stopped,minute:60})[2].level<model.sample({...original,minute:60})[2].level);
const gateEvents=H.changes([],30,100);
const gated={...original,gate:100,gateAt:30,gateEvents};
assert.equal(model.sample({...gated,minute:30})[2].level,model.sample(original)[2].level,'opening a gate cannot instantly jump the water level');
assert.ok(model.sample({...gated,minute:35})[2].level<model.sample({...original,minute:35})[2].level);
assert.equal(model.sample({...gated,minute:40})[1].level,model.sample({...original,minute:40})[1].level,'the downstream effect must wait for travel time');
assert.ok(model.sample({...gated,minute:75})[1].level>model.sample({...original,minute:75})[1].level);
assert.equal(H.rainfall(original,39),90);assert.equal(H.rainfall(original,40),0);
assert.ok(model.sample({...original,minute:120})[2].level<model.sample({...original,minute:40})[2].level,'rain stops and the origin recedes');
const changed=H.changes(rainfall,20,60,40);
assert.equal(H.rainfall({rainEvents:changed},19),90);assert.equal(H.rainfall({rainEvents:changed},20),60);assert.equal(H.rainfall({rainEvents:changed},60),0);
const closedAgain=H.changes(gateEvents,60,0);
assert.equal(closedAgain.length,2,'opening and closing are both retained');
assert.equal(model.sample({...gated,gate:0,gateEvents:closedAgain,minute:60})[2].level,model.sample({...gated,minute:60})[2].level);
console.log('PASS: finite rain, gradual gate response, delayed downstream effect, retained input history and replay continuity');
let saved=null;const store={getItem:()=>saved,setItem:(k,v)=>{saved=v}};
let ledger=H.createLedger(store);
ledger.water(early[2],'test');ledger.water(early[2],'test');assert.equal(ledger.list().length,1,'repeated ticks do not duplicate an event');
const record=ledger.list()[0];ledger.handle(record.id);assert.equal(ledger.list()[0].status,'handled');
ledger.water({...early[2],level:early[2].limit+2},'test');assert.equal(ledger.list()[0].status,'pending','escalation reopens a handled event');
ledger.endRun('test');assert.equal(ledger.list()[0].status,'ended');
ledger.add({type:'inspection',station:0,status:'pending',severity:1,needsReview:true,title:'AI观察待核查',summary:'画面中有一艘船。',observations:[{name:'船',explanation:'可见船体。'}]});
ledger=H.createLedger(store);assert.equal(ledger.list().length,2,'records must survive a browser reload');
assert.ok(!saved.includes('data:image')&&!saved.includes('blob:'));
const loaded=JSON.parse(saved);loaded.records.push({id:'bad',type:'inspection',station:999,status:'pending',title:'bad',at:new Date().toISOString()});saved=JSON.stringify(loaded);assert.equal(H.createLedger(store).list().length,2,'invalid stored station IDs are discarded');
const broken=H.createLedger({getItem(){throw Error('blocked')},setItem(){throw Error('blocked')}});broken.water(early[2],'offline');assert.equal(broken.list().length,1);assert.equal(broken.available(),false);
console.log('PASS: deterministic rainfall and delays, independent lakes, virtual gate tradeoff, severity boundaries, event deduplication/escalation/recovery, persistence, invalid storage and storage-denied fallback');
